"""Render and install one project's OpenCode state.

Inputs identify the renderer, generated project specification, managed output
directory, and repository. The script preserves user-owned project files.
"""

import argparse
import os
import pathlib
import re
import subprocess
import tempfile
from dev_shell_scripts import copy_if_changed


CORPORATE_VARIABLE = re.compile(r"\$(CORP_[A-Z_]+)")
GENERATED_AGENT = "<!-- Generated by render-opencode-project.py"


def replace_corporate_variables(content):
    missing = sorted({match.group(1) for match in CORPORATE_VARIABLE.finditer(content) if match.group(1) not in os.environ})
    if missing:
        raise ValueError(f"required corporate environment variable(s) unset: {', '.join(missing)}")
    return CORPORATE_VARIABLE.sub(lambda match: os.environ[match.group(1)], content)


def can_replace(destination):
    if not destination.exists() and not destination.is_symlink():
        return True
    if destination.is_symlink():
        return True
    if not destination.is_file():
        return False
    content = destination.read_text()
    return GENERATED_AGENT in content


def sync_entry(source, destination):
    if source.is_symlink():
        if can_replace(destination):
            destination.unlink(missing_ok=True)
            destination.symlink_to(os.readlink(source))
        return
    if source.is_file() and can_replace(destination):
        copy_if_changed(source, destination, 0o644)


def ensure_project_link(project_directory, repository_directory):
    if not (repository_directory / ".git").is_dir():
        return
    target = repository_directory / ".opencode"
    if not target.exists() or target.is_symlink():
        target.unlink(missing_ok=True)
        target.symlink_to(project_directory)
    else:
        print(f"warn: preserving real {target}", file=os.sys.stderr)
    exclude_file = repository_directory / ".git" / "info" / "exclude"
    exclude_file.parent.mkdir(parents=True, exist_ok=True)
    exclude_file.touch()
    entries = exclude_file.read_text().splitlines()
    if ".opencode" not in entries:
        with exclude_file.open("a") as output:
            output.write("\n.opencode\n")


parser = argparse.ArgumentParser()
parser.add_argument("--renderer", required=True)
parser.add_argument("--spec", required=True)
parser.add_argument("--project-directory", required=True)
parser.add_argument("--repository-directory", required=True)
arguments = parser.parse_args()

project_directory = pathlib.Path(arguments.project_directory)
repository_directory = pathlib.Path(arguments.repository_directory)
project_directory.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
project_directory.parent.chmod(0o700)

with tempfile.TemporaryDirectory(
    prefix=f"{project_directory.name}.tmp.", dir=project_directory.parent
) as temporary_directory:
    temporary_directory = pathlib.Path(temporary_directory)
    subprocess.run(
        [
            os.sys.executable,
            arguments.renderer,
            "--spec",
            arguments.spec,
            "--output",
            str(temporary_directory),
        ],
        check=True,
    )
    project_directory.mkdir(mode=0o700, exist_ok=True)
    try:
        configuration = replace_corporate_variables(
            (temporary_directory / "opencode.jsonc").read_text().replace(
                str(temporary_directory), str(project_directory)
            )
        )
    except ValueError as error:
        print(f"warn: {error} — preserving the previous OpenCode configuration", file=os.sys.stderr)
        raise SystemExit(0)
    temporary_configuration = temporary_directory / "opencode.jsonc.resolved"
    temporary_configuration.write_text(configuration)
    copy_if_changed(
        temporary_configuration,
        project_directory / "opencode.jsonc",
        0o600,
    )

    for directory_name in ("skills", "agents"):
        source_directory = temporary_directory / directory_name
        destination_directory = project_directory / directory_name
        destination_directory.mkdir(mode=0o700, exist_ok=True)
        for source in source_directory.iterdir():
            sync_entry(source, destination_directory / source.name)

ensure_project_link(project_directory, repository_directory)
